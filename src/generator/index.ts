function getHealthEmoji(score: number): string {
  if (score >= 80) return '🟢';
  if (score >= 60) return '🟡';
  if (score >= 40) return '🟠';
  return '🔴';
}

function getSeverityEmoji(severity: 'error' | 'warning' | 'info'): string {
  switch (severity) {
    case 'error': return '🔴';
    case 'warning': return '🟡';
    case 'info': return '🔵';
  }
}

function getComplexityIndicator(complexity: number): string {
  if (complexity <= 5) return '(low)';
  if (complexity <= 10) return '(moderate)';
  if (complexity <= 20) return '(high)';
  return '(very high ⚠️)';
}

function getHealthGrade(score: number): string {
  if (score >= 90) return '**Grade: A** - Excellent! Your codebase is well-maintained.';
  if (score >= 80) return '**Grade: B** - Good. Minor improvements recommended.';
  if (score >= 70) return '**Grade: C** - Fair. Several areas need attention.';
  if (score >= 60) return '**Grade: D** - Needs Work. Significant improvements needed.';
  return '**Grade: F** - Critical. Immediate attention required.';
}

function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}
