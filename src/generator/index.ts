/**
 * Documentation Generator Module
 * Generates markdown documentation from parsed code
 */

import { writeFile, mkdir } from 'fs/promises';
import { dirname, join, basename, relative } from 'path';
import type {
  ParsedFile,
  CodeBlock,
  DocumentationEntry,
  Config,
  HealthScore
} from '../types.js';

export interface GeneratorOptions {
  outputDir: string;
  format: 'markdown' | 'html' | 'json';
  generateTOC: boolean;
  includeSource: boolean;
  projectName?: string;
}

export async function generateDocumentation(
  files: ParsedFile[],
  healthScore: HealthScore,
  options: GeneratorOptions
): Promise<string[]> {
  const generatedFiles: string[] = [];

  await mkdir(options.outputDir, { recursive: true });

  switch (options.format) {
    case 'markdown':
      generatedFiles.push(...await generateMarkdown(files, healthScore, options));
      break;
    case 'json':
      generatedFiles.push(...await generateJSON(files, healthScore, options));
      break;
    case 'html':
      generatedFiles.push(...await generateHTML(files, healthScore, options));
      break;
  }

  return generatedFiles;
}

async function generateMarkdown(
  files: ParsedFile[],
  healthScore: HealthScore,
  options: GeneratorOptions
): Promise<string[]> {
  const generatedFiles: string[] = [];
  const projectName = options.projectName || 'Project';

  // Generate main README/index
  const mainDoc = generateMainDoc(files, healthScore, projectName, options.generateTOC);
  const mainPath = join(options.outputDir, 'README.md');
  await writeFile(mainPath, mainDoc);
  generatedFiles.push(mainPath);

  // Generate API reference
  const apiDoc = generateAPIReference(files);
  const apiPath = join(options.outputDir, 'API.md');
  await writeFile(apiPath, apiDoc);
  generatedFiles.push(apiPath);

  // Generate per-file documentation
  for (const file of files) {
    if (file.blocks.length === 0) continue;

    const fileDoc = generateFileDoc(file, options.includeSource);
    const docPath = join(
      options.outputDir,
      'files',
      file.info.relativePath.replace(/\.[^.]+$/, '.md')
    );

    await mkdir(dirname(docPath), { recursive: true });
    await writeFile(docPath, fileDoc);
    generatedFiles.push(docPath);
  }

  // Generate health report
  const healthDoc = generateHealthReport(healthScore);
  const healthPath = join(options.outputDir, 'HEALTH.md');
  await writeFile(healthPath, healthDoc);
  generatedFiles.push(healthPath);

  return generatedFiles;
}

async function generateJSON(
  files: ParsedFile[],
  healthScore: HealthScore,
  options: GeneratorOptions
): Promise<string[]> {
  const output = {
    projectName: options.projectName || 'Project',
    generatedAt: new Date().toISOString(),
    healthScore,
    files: files.map(f => ({
      path: f.info.relativePath,
      language: f.info.language,
      lines: f.info.lines,
      blocks: f.blocks.map(b => ({
        type: b.type,
        name: b.name,
        line: b.startLine,
        documented: !!b.documentation,
        complexity: b.complexity,
        parameters: b.parameters,
        returnType: b.returnType
      })),
      imports: f.imports,
      exports: f.exports
    }))
  };

  const outputPath = join(options.outputDir, 'documentation.json');
  await writeFile(outputPath, JSON.stringify(output, null, 2));
  return [outputPath];
}

async function generateHTML(
  files: ParsedFile[],
  healthScore: HealthScore,
  options: GeneratorOptions
): Promise<string[]> {
  const projectName = options.projectName || 'Project';
  const html = generateHTMLDocument(files, healthScore, projectName);
  const outputPath = join(options.outputDir, 'index.html');
  await writeFile(outputPath, html);
  return [outputPath];
}

function generateMainDoc(
  files: ParsedFile[],
  healthScore: HealthScore,
  projectName: string,
  includeTOC: boolean
): string {
  const totalFunctions = files.reduce((sum, f) =>
    sum + f.blocks.filter(b => b.type === 'function' || b.type === 'method').length, 0);
  const totalClasses = files.reduce((sum, f) =>
    sum + f.blocks.filter(b => b.type === 'class').length, 0);
  const totalInterfaces = files.reduce((sum, f) =>
    sum + f.blocks.filter(b => b.type === 'interface').length, 0);
  const totalLines = files.reduce((sum, f) => sum + f.info.lines, 0);

  const languageStats = new Map<string, number>();
  for (const file of files) {
    const count = languageStats.get(file.info.language) || 0;
    languageStats.set(file.info.language, count + 1);
  }

  let doc = `# ${projectName} Documentation

> Auto-generated by DocuMate

## Overview

| Metric | Value |
|--------|-------|
| Total Files | ${files.length} |
| Total Lines | ${totalLines.toLocaleString()} |
| Functions/Methods | ${totalFunctions} |
| Classes | ${totalClasses} |
| Interfaces/Types | ${totalInterfaces} |
| Health Score | ${getHealthEmoji(healthScore.overall)} ${healthScore.overall}/100 |

## Language Breakdown

| Language | Files |
|----------|-------|
${Array.from(languageStats.entries())
  .sort((a, b) => b[1] - a[1])
  .map(([lang, count]) => `| ${lang} | ${count} |`)
  .join('\n')}

## Health Summary

- **Documentation**: ${healthScore.categories.documentation}/100
- **Complexity**: ${healthScore.categories.complexity}/100
- **Structure**: ${healthScore.categories.structure}/100
- **Maintainability**: ${healthScore.categories.maintainability}/100

${healthScore.issues.length > 0 ? `
### Issues Found

${healthScore.issues.slice(0, 10).map(issue =>
  `- ${getSeverityEmoji(issue.severity)} **${issue.rule}**: ${issue.message}${issue.file ? ` (${issue.file}:${issue.line})` : ''}`
).join('\n')}

${healthScore.issues.length > 10 ? `\n_...and ${healthScore.issues.length - 10} more issues_\n` : ''}
` : ''}

${healthScore.suggestions.length > 0 ? `
### Suggestions

${healthScore.suggestions.map(s => `- ${s}`).join('\n')}
` : ''}
`;

  if (includeTOC) {
    doc += `
## Table of Contents

### Files

${files.map(f => `- [${f.info.relativePath}](files/${f.info.relativePath.replace(/\.[^.]+$/, '.md')})`).join('\n')}

### Quick Links

- [API Reference](API.md)
- [Health Report](HEALTH.md)
`;
  }

  return doc;
}

function generateAPIReference(files: ParsedFile[]): string {
  let doc = `# API Reference

> Auto-generated by DocuMate

`;

  // Group by type
  const functions: { block: CodeBlock; file: ParsedFile }[] = [];
  const classes: { block: CodeBlock; file: ParsedFile }[] = [];
  const interfaces: { block: CodeBlock; file: ParsedFile }[] = [];
  const types: { block: CodeBlock; file: ParsedFile }[] = [];

  for (const file of files) {
    for (const block of file.blocks) {
      const entry = { block, file };
      switch (block.type) {
        case 'function':
        case 'method':
          functions.push(entry);
          break;
        case 'class':
          classes.push(entry);
          break;
        case 'interface':
          interfaces.push(entry);
          break;
        case 'type':
          types.push(entry);
          break;
      }
    }
  }

  if (classes.length > 0) {
    doc += `## Classes

| Class | File | Documented | Complexity |
|-------|------|------------|------------|
${classes.map(({ block, file }) =>
  `| \`${block.name}\` | ${file.info.relativePath}:${block.startLine} | ${block.documentation ? '✅' : '❌'} | ${block.complexity || '-'} |`
).join('\n')}

`;

    for (const { block, file } of classes) {
      doc += generateBlockDoc(block, file.info.relativePath);
    }
  }

  if (interfaces.length > 0) {
    doc += `## Interfaces

| Interface | File | Documented |
|-----------|------|------------|
${interfaces.map(({ block, file }) =>
  `| \`${block.name}\` | ${file.info.relativePath}:${block.startLine} | ${block.documentation ? '✅' : '❌'} |`
).join('\n')}

`;
  }

  if (functions.length > 0) {
    doc += `## Functions

| Function | File | Parameters | Returns | Documented | Complexity |
|----------|------|------------|---------|------------|------------|
${functions.map(({ block, file }) =>
  `| \`${block.name}\` | ${file.info.relativePath}:${block.startLine} | ${block.parameters?.length || 0} | ${block.returnType || '-'} | ${block.documentation ? '✅' : '❌'} | ${block.complexity || '-'} |`
).join('\n')}

`;

    for (const { block, file } of functions) {
      doc += generateBlockDoc(block, file.info.relativePath);
    }
  }

  return doc;
}

function generateBlockDoc(block: CodeBlock, filePath: string): string {
  let doc = `### \`${block.name}\`

**File:** \`${filePath}:${block.startLine}\`
**Type:** ${block.type}
`;

  if (block.complexity) {
    doc += `**Complexity:** ${block.complexity} ${getComplexityIndicator(block.complexity)}\n`;
  }

  if (block.documentation) {
    doc += `\n${block.documentation}\n`;
  }

  if (block.parameters && block.parameters.length > 0) {
    doc += `
#### Parameters

| Name | Type | Optional | Default |
|------|------|----------|---------|
${block.parameters.map(p =>
  `| \`${p.name}\` | ${p.type || '-'} | ${p.optional ? 'Yes' : 'No'} | ${p.defaultValue || '-'} |`
).join('\n')}
`;
  }

  if (block.returnType) {
    doc += `\n#### Returns\n\n\`${block.returnType}\`\n`;
  }

  doc += '\n---\n\n';
  return doc;
}

function generateFileDoc(file: ParsedFile, includeSource: boolean): string {
  let doc = `# ${file.info.relativePath}

**Language:** ${file.info.language}
**Lines:** ${file.info.lines}
**Size:** ${formatBytes(file.info.size)}

`;

  if (file.imports.length > 0) {
    doc += `## Imports

${file.imports.map(i => `- \`${i.source}\`: ${i.items.join(', ')}`).join('\n')}

`;
  }

  if (file.exports.length > 0) {
    doc += `## Exports

${file.exports.map(e => `- \`${e.name}\` (${e.type})`).join('\n')}

`;
  }

  if (file.blocks.length > 0) {
    doc += `## Contents

`;

    for (const block of file.blocks) {
      doc += `### ${block.type}: \`${block.name}\`

**Lines:** ${block.startLine}-${block.endLine}
`;

      if (block.complexity) {
        doc += `**Complexity:** ${block.complexity} ${getComplexityIndicator(block.complexity)}\n`;
      }

      if (block.documentation) {
        doc += `\n> ${block.documentation.split('\n').join('\n> ')}\n`;
      } else {
        doc += `\n⚠️ *No documentation found*\n`;
      }

      if (block.parameters && block.parameters.length > 0) {
        doc += `\n**Parameters:**\n${block.parameters.map(p =>
          `- \`${p.name}\`${p.type ? `: ${p.type}` : ''}${p.optional ? ' (optional)' : ''}`
        ).join('\n')}\n`;
      }

      if (block.returnType) {
        doc += `\n**Returns:** \`${block.returnType}\`\n`;
      }

      if (includeSource) {
        doc += `\n<details>
<summary>Source Code</summary>

\`\`\`${file.info.language}
${block.content}
\`\`\`

</details>
`;
      }

      doc += '\n---\n\n';
    }
  }

  return doc;
}

function generateHealthReport(healthScore: HealthScore): string {
  return `# Codebase Health Report

> Auto-generated by DocuMate

## Overall Score: ${getHealthEmoji(healthScore.overall)} ${healthScore.overall}/100

${getHealthGrade(healthScore.overall)}

## Category Breakdown

| Category | Score | Status |
|----------|-------|--------|
| Documentation | ${healthScore.categories.documentation}/100 | ${getHealthEmoji(healthScore.categories.documentation)} |
| Complexity | ${healthScore.categories.complexity}/100 | ${getHealthEmoji(healthScore.categories.complexity)} |
| Structure | ${healthScore.categories.structure}/100 | ${getHealthEmoji(healthScore.categories.structure)} |
| Maintainability | ${healthScore.categories.maintainability}/100 | ${getHealthEmoji(healthScore.categories.maintainability)} |

## Issues (${healthScore.issues.length} total)

${healthScore.issues.length === 0 ? '✅ No issues found!' : ''}

${['error', 'warning', 'info'].map(severity => {
  const issues = healthScore.issues.filter(i => i.severity === severity);
  if (issues.length === 0) return '';

  return `### ${getSeverityEmoji(severity as any)} ${severity.charAt(0).toUpperCase() + severity.slice(1)}s (${issues.length})

${issues.map(issue =>
  `- **${issue.rule}**: ${issue.message}${issue.file ? `\n  - File: \`${issue.file}:${issue.line}\`` : ''}`
).join('\n')}
`;
}).filter(Boolean).join('\n')}

## Suggestions for Improvement

${healthScore.suggestions.length === 0 ? 'No suggestions - your code looks good!' :
  healthScore.suggestions.map((s, i) => `${i + 1}. ${s}`).join('\n')}

---

*Report generated on ${new Date().toISOString()}*
`;
}

